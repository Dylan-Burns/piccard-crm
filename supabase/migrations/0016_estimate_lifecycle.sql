-- First real view of a sent estimate. Anything else is a no-op.
create or replace function public.record_estimate_view(p_token uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare e record;
begin
  if not private.is_service_role() then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;
  select id, opportunity_id, status, estimate_number, version into e from public.estimates where public_token = p_token for update;
  if not found or e.status <> 'sent' then
    return jsonb_build_object('ok', true, 'changed', false);
  end if;
  update public.estimates set status = 'viewed', viewed_at = now() where id = e.id;
  perform private.log_activity('estimate_viewed', e.opportunity_id, null,
    'Customer viewed estimate ' || private.estimate_label(e.estimate_number, e.version), jsonb_build_object('estimate_id', e.id));
  return jsonb_build_object('ok', true, 'changed', true);
end $$;

-- Approval: wins the deal (job, invoices) through mark_opportunity_won, then records who approved.
create or replace function public.accept_estimate(p_token uuid, p_name text, p_ip text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  e record;
  v_name text := nullif(trim(p_name), '');
  v_ip inet;
  v_won jsonb;
begin
  if not private.is_service_role() then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;
  select id, opportunity_id, status, estimate_number, version, valid_until into e
    from public.estimates where public_token = p_token for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'not_found', 'message', 'Estimate not found');
  end if;
  if e.status = 'accepted' then
    return jsonb_build_object('ok', true, 'already', true, 'opportunity_id', e.opportunity_id, 'estimate_id', e.id);
  end if;
  if e.status not in ('sent', 'viewed') or (e.valid_until is not null and e.valid_until < private.business_today()) then
    return jsonb_build_object('ok', false, 'code', 'not_available', 'message', 'This estimate is no longer available');
  end if;
  if v_name is null or length(v_name) < 2 or length(v_name) > 200 then
    return jsonb_build_object('ok', false, 'code', 'name_required', 'message', 'Type your full name to approve');
  end if;
  begin
    v_ip := nullif(trim(p_ip), '')::inet;
  exception when others then
    v_ip := null;
  end;

  v_won := public.mark_opportunity_won(e.opportunity_id, e.id);
  if not coalesce((v_won->>'ok')::boolean, false) then
    return v_won;   -- nothing has been written
  end if;

  update public.estimates set accepted_name = v_name, accepted_ip = v_ip where id = e.id;
  perform private.log_activity('estimate_accepted', e.opportunity_id, null,
    'Customer approved estimate ' || private.estimate_label(e.estimate_number, e.version),
    jsonb_build_object('estimate_id', e.id, 'name', v_name));
  return jsonb_build_object('ok', true, 'opportunity_id', e.opportunity_id, 'estimate_id', e.id,
                            'job_id', v_won->'job_id', 'job_number', v_won->'job_number');
end $$;

-- Decline: the deal is not lost automatically; the rep gets a task to call.
create or replace function public.decline_estimate(p_token uuid, p_reason text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare e record;
begin
  if not private.is_service_role() then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;
  select id, opportunity_id, status, estimate_number, version into e from public.estimates where public_token = p_token for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'not_found', 'message', 'Estimate not found');
  end if;
  if e.status = 'declined' then
    return jsonb_build_object('ok', true, 'already', true, 'opportunity_id', e.opportunity_id, 'estimate_id', e.id);
  end if;
  if e.status not in ('sent', 'viewed') then
    return jsonb_build_object('ok', false, 'code', 'not_available', 'message', 'This estimate is no longer available');
  end if;
  update public.estimates
     set status = 'declined', declined_at = now(), decline_reason = nullif(left(trim(p_reason), 1000), '')
   where id = e.id;
  perform private.log_activity('estimate_declined', e.opportunity_id, null,
    'Customer declined estimate ' || private.estimate_label(e.estimate_number, e.version),
    jsonb_build_object('estimate_id', e.id, 'reason', nullif(left(trim(p_reason), 1000), '')));
  perform private.create_auto_task(e.opportunity_id, null, 'declined_followup', 'Customer declined estimate — call', now() + interval '1 hour');
  return jsonb_build_object('ok', true, 'opportunity_id', e.opportunity_id, 'estimate_id', e.id);
end $$;

-- ---------------------------------------------------------------------------
-- run_nightly_maintenance (service role): expire estimates past their valid-until date, and
-- give every open deal with no next step a task (§4.4). Safe to run more than once a day.
-- ---------------------------------------------------------------------------
create or replace function public.run_nightly_maintenance() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  e record;
  o record;
  v_today date := private.business_today();
  v_expired integer := 0;
  v_stale integer := 0;
begin
  if not private.is_service_role() then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;

  for e in
    select es.id, es.opportunity_id, es.estimate_number, es.version
      from public.estimates es
     where es.status in ('sent', 'viewed') and es.valid_until is not null and es.valid_until < v_today
     for update of es
  loop
    update public.estimates set status = 'expired' where id = e.id;
    perform private.log_activity('estimate_expired', e.opportunity_id, null,
      'Estimate ' || private.estimate_label(e.estimate_number, e.version) || ' expired', jsonb_build_object('estimate_id', e.id));
    perform private.create_auto_task(e.opportunity_id, null, 'estimate_expired', 'Estimate expired — revise or close', now());
    v_expired := v_expired + 1;
  end loop;

  for o in
    select opp.id from public.opportunities opp
     where opp.stage not in ('won', 'lost')
       and not exists (select 1 from public.tasks t where t.opportunity_id = opp.id and t.status = 'open')
       and not exists (select 1 from public.appointments a
                        where a.opportunity_id = opp.id and a.status = 'scheduled' and a.starts_at > now())
  loop
    perform private.create_auto_task(o.id, null, 'stale_deal', 'No next step set — decide what happens next', now());
    v_stale := v_stale + 1;
  end loop;

  return jsonb_build_object('ok', true, 'expired', v_expired, 'stale', v_stale);
end $$;

revoke execute on function public.mark_estimate_sent(uuid, text, text), public.revise_estimate(uuid),
  public.record_estimate_view(uuid), public.accept_estimate(uuid, text, text), public.decline_estimate(uuid, text),
  public.run_nightly_maintenance() from public, anon, authenticated;
grant execute on function public.mark_estimate_sent(uuid, text, text), public.revise_estimate(uuid) to authenticated, service_role;
grant execute on function public.record_estimate_view(uuid), public.accept_estimate(uuid, text, text),
  public.decline_estimate(uuid, text), public.run_nightly_maintenance() to service_role;
